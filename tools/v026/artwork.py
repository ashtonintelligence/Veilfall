def rgb(c):
    if isinstance(c,str):
        c=c.lstrip('#');return tuple(int(c[i:i+2],16) for i in (0,2,4))
    return c[:3]

class Painter:
    def __init__(self):self.im=Image.new('RGBA',(256*S,256*S),(0,0,0,0))
    def shape(self,pts,color,outline=INK,width=1.5):
        pts=[(round(x*S),round(y*S)) for x,y in pts]
        mask=Image.new('L',self.im.size,0);ImageDraw.Draw(mask).polygon(pts,fill=255)
        col=rgb(color);grad=Image.new('RGBA',self.im.size,(0,0,0,0));d=ImageDraw.Draw(grad)
        for y in range(grad.height):
            f=1.17-.32*y/grad.height
            d.line((0,y,grad.width,y),fill=tuple(max(0,min(255,round(v*f))) for v in col)+(255,))
        grad.putalpha(mask);self.im.alpha_composite(grad)
        if outline:ImageDraw.Draw(self.im).line(pts+[pts[0]],fill=outline,width=max(1,round(width*S)),joint='curve')
    def poly(self,pts,color,outline=INK,width=1.4):self.shape(pts,color,outline,width)
    def line(self,pts,color=INK,width=1.5):
        ImageDraw.Draw(self.im).line([(round(x*S),round(y*S)) for x,y in pts],fill=color,width=max(1,round(width*S)),joint='curve')
    def ellipse(self,box,color,outline=INK,width=1.4):
        x0,y0,x1,y1=box
        pts=[((x0+x1)/2+(x1-x0)/2*math.cos(t*math.pi/32),(y0+y1)/2+(y1-y0)/2*math.sin(t*math.pi/32)) for t in range(64)]
        self.poly(pts,color,outline,width)
    def rect(self,b,c,outline=INK,width=1.4):
        x0,y0,x1,y1=b;self.poly([(x0,y0),(x1,y0),(x1,y1),(x0,y1)],c,outline,width)
    def face(self,x,y,skin=SKIN,beard=False):
        self.poly([(x-5,y+12),(x-5,y+23),(x+8,y+26),(x+10,y+12)],skin)
        self.poly([(x-11,y-12),(x+8,y-15),(x+16,y-3),(x+13,y+3),(x+16,y+8),(x+10,y+11),(x+8,y+18),(x-1,y+20),(x-10,y+12),(x-13,y)],skin)
        self.poly([(x-12,y-8),(x-5,y-10),(x-6,y+10),(x,y+19),(x-9,y+11)],'#815940',None)
        self.line([(x+2,y-1),(x+9,y)],INK,1.5)
        self.line([(x+10,y+1),(x+7,y+7),(x+11,y+8)],'#79573f',1)
        self.line([(x+2,y+13),(x+9,y+13)],INK,1)
        self.ellipse((x-13,y+1,x-7,y+10),skin,width=.7)
        if beard:self.poly([(x-7,y+11),(x+1,y+15),(x+12,y+10),(x+10,y+20),(x+1,y+24),(x-7,y+19)],'#40342d',None)
    def hand(self,x,y,c=SKIN):
        self.poly([(x-6,y-4),(x+3,y-6),(x+7,y-1),(x+5,y+6),(x-2,y+8),(x-7,y+3)],c,width=1)
        self.line([(x-3,y),(x+2,y+2),(x+4,y+5)],'#755340',.9)
    def boot(self,x,y,w=19,flip=False,c='#303335'):
        pts=[(x,y),(x+w,y-1),(x+w-1,y+22),(x+w+8,y+27),(x+w+7,y+32),(x-2,y+31)]
        if flip:pts=[(2*x+w-px,py) for px,py in pts]
        self.poly(pts,c);self.line([(x+2,y+26),(x+w+5,y+28)],'#717477',1)
    def rifle(self,x,y,angle=0,modern=False,energy=False,length=111):
        a=math.radians(angle)
        def pt(p):
            u,v=p;return(x+u*math.cos(a)-v*math.sin(a),y+u*math.sin(a)+v*math.cos(a))
        def pol(p,c):self.poly([pt(q) for q in p],c,width=1.1)
        if modern:
            pol([(0,-7),(19,-8),(26,-3),(63,-3),(63,8),(24,8),(17,13),(2,11)],'#24313b')
            pol([(33,8),(44,8),(46,24),(34,24)],'#222b32')
            pol([(45,-6),(72,-6),(72,6),(45,6)],NAVY if energy else '#4d5757')
            pol([(72,-3),(length,-3),(length,2),(72,2)],STEEL)
            pol([(41,-14),(64,-14),(68,-9),(38,-9)],SCARLET if energy else '#384044')
            self.line([pt((47,-2)),pt((length-6,-2))],'#87d7ed' if energy else '#b1b7ae',2)
            if energy:pol([(length-5,-6),(length+3,-6),(length+3,5),(length-5,5)],GOLD)
        else:
            pol([(0,-6),(13,-8),(23,-2),(70,-2),(73,4),(21,5),(9,12),(0,12)],BROWN)
            pol([(29,-5),(length,-5),(length,-1),(29,-1)],STEEL)
            pol([(30,5),(36,5),(35,10),(29,10)],'#43352b')
            for k in (54,72):self.line([pt((k,-6)),pt((k,5))],GOLD,1.5)
        return pt
    def finish(self):return self.im.resize((256,256),Image.Resampling.LANCZOS)

