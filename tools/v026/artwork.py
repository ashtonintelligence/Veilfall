def fit(src,size,maxw,maxh,bottom):
    box=src.getchannel('A').getbbox()
    if box is None:raise ValueError('Empty source figure')
    crop=src.crop(box);scale=min(maxw/crop.width,maxh/crop.height)
    wh=(max(1,round(crop.width*scale)),max(1,round(crop.height*scale)))
    crop=crop.resize(wh,Image.Resampling.LANCZOS)
    out=Image.new('RGBA',(size,size),(0,0,0,0));out.alpha_composite(crop,((size-wh[0])//2,bottom-wh[1]))
    return out

def make_assets():
    result={}
    for name,artist in ARTISTS.items():
        portrait=fit(artist(),256,234,234,245);result['UnitPortraits/'+name]=portrait
        icon=Image.new('RGBA',portrait.size,(255,255,255,0));icon.putalpha(portrait.getchannel('A'))
